package app.getknit.knit.moderation

/**
 * Screens a name — a display name, a status line, a group's name, a Meshtastic board's long name — against the
 * word lists (ADR 2026-11.y4pc). Pure Kotlin, no Android dependencies, so it is unit-tested directly.
 *
 * A name is not a sentence. It is often one run-together handle, so the message filter's whole-word rule alone misses
 * most of the shapes a username takes (`BigD1ck69`, `xXslurXx`), and the toxicity model, measured on name data, caught
 * about one offensive name in a hundred. So a name is read three ways:
 *
 *  - **as split variants.** The name as written, with camelCase boundaries split, and with digit runs as separators,
 *    each run through the whole-word [LexicalTextFilter]. Trying the name as written as well keeps leetspeak working.
 *  - **inside its words**, for [embeddable] terms only: those that no dictionary word or real name holds, so "pikey"
 *    is found in "pikeyboy" while "dick" is never looked for inside "Dickson". A token is cut at each of
 *    [exclusions] first ("spikey" holds "pikey"), and a digit counts as a leet letter there only between letters, so
 *    `ashish17tripathi` is not read as holding a profanity.
 *  - **with real names allowed.** A profanity term that is also a given name or surname ([allowedNames]: Dick, Coon,
 *    Shota) passes as a word written in plain letters, so "Dick Smith" passes and `BigD1ck69` does not. A term on
 *    the slur list never does, whatever the allow-list says.
 *
 * [Audience.PUBLIC] is what strangers see — a person's name and status, a board's long name — and takes both lists, the
 * Nearby room's rules. [Audience.MEMBERS] is a group's name, seen only by its members, and takes the slur list alone,
 * the private scope of ADR 2026-10.d62w. The three name lists are generated by `scripts/gen-name-screen-lists.py`.
 */
class NameScreen(
    slurs: Collection<String>,
    profanity: Collection<String>,
    embeddable: Collection<String>,
    exclusions: Collection<String>,
    allowedNames: Collection<String>,
) {
    /** Who sees the name: strangers ([PUBLIC]), or only a group's members ([MEMBERS]). */
    enum class Audience { PUBLIC, MEMBERS }

    private val slurTerms = slurs.map { LexicalTextFilter.normalize(it) }.filter(String::isNotEmpty).toSet()
    private val profanityTerms = profanity.map { LexicalTextFilter.normalize(it) }.filter(String::isNotEmpty).toSet()
    private val allowed = allowedNames.map { LexicalTextFilter.normalize(it) }.filter(String::isNotEmpty).toSet() - slurTerms
    private val slurFilter = LexicalTextFilter(slurTerms, category = TextVerdict.Category.SLUR)
    private val profanityFilter = LexicalTextFilter(profanityTerms, category = TextVerdict.Category.PROFANITY)
    private val inside = embeddable.map { LexicalTextFilter.normalize(it) }.filter { it.length >= MIN_INSIDE }.toSet()
    private val insideSlurs = inside intersect slurTerms
    private val insideProfanity = (inside intersect profanityTerms) - slurTerms
    private val cuts = exclusions.map { LexicalTextFilter.normalize(it) }.filter(String::isNotEmpty)

    /** Flagged with [TextVerdict.Category.SLUR] or [TextVerdict.Category.PROFANITY], or [TextVerdict.ALLOWED]. */
    fun check(
        name: String,
        audience: Audience,
    ): TextVerdict {
        if (name.isBlank()) return TextVerdict.ALLOWED
        val variants = variants(name)
        if (variants.any { slurFilter.check(it).flagged } || holds(name, insideSlurs)) return SLUR
        if (audience == Audience.MEMBERS) return TextVerdict.ALLOWED
        val rest = withoutRealNames(name)
        if (variants(rest).any { profanityFilter.check(it).flagged } || holds(rest, insideProfanity)) return PROFANITY
        return TextVerdict.ALLOWED
    }

    /** [name] with every word that is an allowed real name, written in plain letters, taken out ("Dick Smith" → " Smith"). */
    private fun withoutRealNames(name: String): String =
        if (allowed.isEmpty()) {
            name
        } else {
            splitCamel(name).replace(LETTER_RUN) {
                if (LexicalTextFilter.normalize(it.value) in
                    allowed
                ) {
                    " "
                } else {
                    it.value
                }
            }
        }

    private fun variants(name: String): List<String> {
        val spaced = name.replace(DIGIT_RUN, " ")
        return listOf(name, splitCamel(name), spaced, splitCamel(spaced)).distinct()
    }

    private fun splitCamel(s: String): String = s.replace(LOWER_THEN_UPPER, " ").replace(UPPER_THEN_WORD, " ")

    /** Whether a piece of [name], read inside its words, holds one of [terms]. */
    private fun holds(
        name: String,
        terms: Set<String>,
    ): Boolean {
        if (terms.isEmpty()) return false
        for (token in name.split(TOKEN_SEPARATORS)) {
            if (token.isEmpty()) continue
            for (word in LexicalTextFilter.normalize(flankedLeet(token)).split(NOT_LETTERS)) {
                if (word.isEmpty()) continue
                for (piece in cut(word)) {
                    val collapsed = LexicalTextFilter.collapseRuns(piece)
                    if (terms.any { piece.contains(it) || collapsed.contains(it) }) return true
                }
            }
        }
        return false
    }

    /** A digit stands for its leet letter only with a letter on each side (`sh1t`); anywhere else it separates. */
    private fun flankedLeet(token: String): String {
        val out = StringBuilder(token.length)
        for (i in token.indices) {
            val ch = token[i]
            if (!ch.isDigit()) {
                out.append(ch)
                continue
            }
            val between = i > 0 && i < token.lastIndex && token[i - 1].isLetter() && token[i + 1].isLetter()
            out.append(LexicalTextFilter.leetLetter(ch).takeIf { between } ?: ' ')
        }
        return out.toString()
    }

    /** [word] split at every exclusion it holds, so "spikeyboy" is read as "boy". */
    private fun cut(word: String): List<String> {
        var pieces = listOf(word)
        for (c in cuts) pieces = pieces.flatMap { it.split(c) }
        return pieces.filter(String::isNotEmpty)
    }

    private companion object {
        const val MIN_INSIDE = 4
        val SLUR = TextVerdict(allowed = false, category = TextVerdict.Category.SLUR, score = 1f)
        val PROFANITY = TextVerdict(allowed = false, category = TextVerdict.Category.PROFANITY, score = 1f)
        val DIGIT_RUN = Regex("\\p{Nd}+")
        val LOWER_THEN_UPPER = Regex("(?<=\\p{Ll})(?=\\p{Lu})")
        val UPPER_THEN_WORD = Regex("(?<=\\p{Lu})(?=\\p{Lu}\\p{Ll})")

        // Whitespace, punctuation and symbols split a name into tokens, except the four symbols the filter reads as
        // leet letters (@ $ ! |), which stay inside the token they are part of.
        val TOKEN_SEPARATORS = Regex("[\\s\\p{P}\\p{S}&&[^@$!|]]+")
        val NOT_LETTERS = Regex("[^a-z]+")
        val LETTER_RUN = Regex("\\p{L}+")
    }
}
